#!/usr/bin/env node
/**
 * update-custom-tricks.mjs
 *
 * Merges your custom tricks into the app so they are baked into the repo
 * and available on every device that visits the hosted site.
 *
 * USAGE:
 *   node update-custom-tricks.mjs            (reads custom-tricks.json)
 *   node update-custom-tricks.mjs path.json  (reads any exported backup)
 *
 * The script takes all tricks from the input file that are NOT built-in
 * tricks and writes them into js/custom-tricks.js. Commit the updated
 * js/custom-tricks.js (and custom-tricks.json) to GitHub.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const inputPath = path.resolve(ROOT, process.argv[2] || 'custom-tricks.json');
const outputPath = path.resolve(ROOT, 'js', 'custom-tricks.js');

// Load built-in ids from builtins.js so we never duplicate them.
const builtinSrc = fs.readFileSync(path.resolve(ROOT, 'js', 'builtins.js'), 'utf8');
const builtinIds = [...builtinSrc.matchAll(/id:\s*"([^"]+)"/g)].map(m => m[1]);

if (!fs.existsSync(inputPath)) {
  console.error(`Input file not found: ${inputPath}`);
  process.exit(1);
}

let parsed;
try {
  const raw = fs.readFileSync(inputPath, 'utf8').replace(/^\uFEFF/, '');
  parsed = JSON.parse(raw);
} catch (e) {
  console.error('Invalid JSON in input file:', e.message);
  process.exit(1);
}

if (!Array.isArray(parsed)) {
  console.error('Input file must contain a JSON array of tricks.');
  process.exit(1);
}

const valid = parsed.filter(t => t && t.id && t.name && Array.isArray(t.moves) && t.moves.length);
const customs = valid.filter(t => !builtinIds.includes(t.id));
const byId = new Map(customs.map(t => [t.id, t]));

// Re-serialize each trick cleanly, keeping only the fields the app uses.
const clean = Array.from(byId.values()).map(t => ({
  id: t.id,
  name: t.name,
  opening: t.opening || 'Custom',
  side: t.side === 'Black' ? 'Black' : 'White',
  tags: Array.isArray(t.tags) ? t.tags : [],
  description: t.description || '',
  moves: t.moves.map(m => ({
    move: m.move,
    san: m.san || '',
    comment: m.comment || ''
  })),
  isCustom: true
}));

let out;
const header = '// Generated by update-custom-tricks.mjs — do not edit by hand.\n';
if (clean.length === 0) {
  out = header + 'export const CUSTOM_TRICKS = [];\n';
} else {
  const items = clean.map(t => '  ' + JSON.stringify(t, null, 2).replace(/\n/g, '\n  '));
  out = header + `export const CUSTOM_TRICKS = [\n${items.join(',\n')}\n];\n`;
}

fs.writeFileSync(outputPath, out, 'utf8');
console.log(`Wrote ${clean.length} custom trick(s) to ${outputPath}`);
if (valid.length !== customs.length) {
  console.log(`Skipped ${valid.length - customs.length} built-in trick(s).`);
}